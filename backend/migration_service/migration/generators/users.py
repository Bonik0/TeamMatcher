CYRILLIC_TO_LATIN = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'yo', 'ж': 'zh', 'з': 'z', 'и': 'i',
    'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't',
    'у': 'u', 'ф': 'f', 'х': 'kh', 'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'shch', 'ъ': '', 'ы': 'y', 'ь': '',
    'э': 'e', 'ю': 'yu', 'я': 'ya'
}


def transliterate(text: str) -> str:
    text = text.lower()
    result = []
    for char in text:
        if char in CYRILLIC_TO_LATIN:
            result.append(CYRILLIC_TO_LATIN[char])
    return ''.join(result)


def get_random_person() -> tuple[str, str, str]:
    gender = random.choice(['male', 'female'])
    if gender == 'male':
        first_name = random.choice(MALE_FIRST_NAMES)
        surname = random.choice(MALE_SURNAMES)
        patronymic = random.choice(MALE_PATRONYMICS)
    else:
        first_name = random.choice(FEMALE_FIRST_NAMES)
        surname = random.choice(FEMALE_SURNAMES)
        patronymic = random.choice(FEMALE_PATRONYMICS)
    return first_name, surname, patronymic


def get_hash(password: str) -> str:
    return bcrypt.hashpw(password.encode(), bcrypt.gensalt()).decode()

def generate_users(password: str, total_count: int, organizers_count: int, path: str) -> None:
    
    total_count = max(0, total_count)
    organizers_count = max(0, min(total_count, organizers_count))
    password_hash = get_hash(password)
    
    users = []

    for user_id in range(1, total_count + 1):

        role = "organizer" if user_id > total_count - organizers_count else "user" 
        
        first_name, surname, patronymic = get_random_person()
        latin_surname = transliterate(surname)
        email = f"{latin_surname}{user_id}@mail.ru"
        
        users.append((user_id, email, first_name, patronymic, surname, password_hash, role))

    pd.DataFrame(
        users, 
        columns=[
            "id", "email", "first_name", "patronymic", "surname", "hash_password", "role"
        ],
    ).to_csv(path, index=False)
    
    
